/* =========================================
   VARIABLES
========================================= */

let selectedQuestions = [];

let currentQuestion = 0;

let score = {
    A: 0,
    B: 0,
    C: 0,
    D: 0
};


/* =========================================
   DOM
========================================= */

const startScreen =
    document.getElementById("start-screen");

const quizScreen =
    document.getElementById("quiz-screen");

const resultScreen =
    document.getElementById("result-screen");

const startButton =
    document.getElementById("start-button");

const restartButton =
    document.getElementById("restart-button");

const questionText =
    document.getElementById("question-text");

const questionNumber =
    document.getElementById("question-number");

const answerLabel =
    document.getElementById("answer-label");

const resultFont =
    document.getElementById("result-font");

const resultDescription =
    document.getElementById("result-description");

const orbs =
    document.querySelectorAll(".orb");


/* =========================================
   SHUFFLE
========================================= */

function shuffle(array) {

    return [...array]
        .sort(() => Math.random() - 0.5);

}


/* =========================================
   START QUIZ
========================================= */

function startQuiz() {

    score = {
        A: 0,
        B: 0,
        C: 0,
        D: 0
    };

    currentQuestion = 0;

    /*
        Pick 10 random questions
        from the 21.
    */

    selectedQuestions =
        shuffle(questions).slice(0, 10);


    startScreen.classList.remove("active");

    resultScreen.classList.remove("active");

    quizScreen.classList.add("active");

    showQuestion();
}


/* =========================================
   SHOW QUESTION
========================================= */

function showQuestion() {

    const question =
        selectedQuestions[currentQuestion];

    questionText.textContent =
        question.question;

    questionNumber.textContent =
        String(currentQuestion + 1)
            .padStart(2, "0");

    answerLabel.textContent =
        "Välj ett tecken";
}


/* =========================================
   ANSWER
========================================= */

function answerQuestion(answer) {

    score[answer]++;

    answerLabel.textContent =
        "Tecknet är registrerat…";


    setTimeout(() => {

        currentQuestion++;


        if (
            currentQuestion >=
            selectedQuestions.length
        ) {

            showResult();

        } else {

            showQuestion();

        }

    }, 450);

}


/* =========================================
   RESULT
========================================= */

function calculateResult() {

    /*
        TEMPORÄR RESULTATLOGIK.

        Detta kommer senare ersättas med
        en riktig typografisk personlighets-
        algoritm där varje svar påverkar
        olika egenskaper.
    */

    const total =
        score.A * 1 +
        score.B * 2 +
        score.C * 3 +
        score.D * 4;


    const index =
        total % typefaces.length;


    return typefaces[index];

}


/* =========================================
   SHOW RESULT
========================================= */

function showResult() {

    const result =
        calculateResult();


    quizScreen.classList.remove("active");

    resultScreen.classList.add("active");


    /*
        Ta bort gamla font-klasser
    */

    typefaces.forEach(font => {

        resultFont.classList.remove(
            font.className
        );

    });


    /*
        Lägg till rätt fontklass
    */

    resultFont.classList.add(
        result.className
    );


    resultFont.textContent =
        result.name;


    resultDescription.textContent =
        result.description;

}


/* =========================================
   BUTTON EVENTS
========================================= */

startButton.addEventListener(
    "click",
    startQuiz
);


restartButton.addEventListener(
    "click",
    startQuiz
);


/* =========================================
   ORB EVENTS
========================================= */

orbs.forEach(orb => {

    orb.addEventListener(
        "click",
        () => {

            const answer =
                orb.dataset.answer;

            answerQuestion(answer);

        }
    );

});
